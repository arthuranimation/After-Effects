  // Paint a pixel map: rows of characters, '.' = transparent.
  function pix(S, rows, leg, ox = 0, oy = 0) {
    const L = leg ? Object.assign({}, BASE, leg) : BASE;
    for (let y = 0; y < rows.length; y++) {
      const row = rows[y];
      for (let x = 0; x < row.length; x++) {
        const ch = row[x];
        if (ch === '.' || ch === ' ') continue;
        const c = L[ch];
        if (c) S.px(ox + x, oy + y, c);
        else console.warn('icon: unknown pixel key "' + ch + '"');
      }
    }
  }

