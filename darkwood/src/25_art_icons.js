  // ==============================================================
  // RINGS — torus shading, gem / rune.
  // ==============================================================
  function band(S, cx, cy, rxo, ryo, rxi, ryi, tones, gamma = 1, dyi = 0) {
    const n = tones.length - 1;
    for (let y = 0; y < S.h; y++) for (let x = 0; x < S.w; x++) {
      const px = x + 0.5 - cx, py = y + 0.5 - cy;
      const eo = (px / rxo) ** 2 + (py / ryo) ** 2, ei = (px / rxi) ** 2 + ((py - dyi) / ryi) ** 2;
      if (eo > 1 || ei < 1) continue;
      const ko = 1 / Math.sqrt(eo), ki = 1 / Math.sqrt(ei);
      const t = (1 - ki) / Math.max(0.001, ko - ki), sc = Math.max(-1, Math.min(1, 2 * t - 1));
      const d = Math.hypot(px, py) || 1;
      const I = S.lit(DW.kit.norm3([px / d * sc, py / d * sc, Math.sqrt(1 - sc * sc)]), { spec: 0.5 });
      S.px(x, y, tones[Math.max(0, Math.min(n, Math.round(Math.pow(Math.max(0, I), gamma) * n)))]);
    }
  }

