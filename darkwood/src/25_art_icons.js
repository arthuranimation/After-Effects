  // Thick quadratic-bezier stroke, width w0 → wm (middle) → w1; colour by
  // normalised distance from the centre line (k 0..1) and position t.
  function stroke(S, P0, C, P1, w0, wm, w1, colFn) {
    const pts = [];
    for (let i = 0; i <= 48; i++) {
      const t = i / 48, it = 1 - t;
      pts.push([it * it * P0[0] + 2 * it * t * C[0] + t * t * P1[0], it * it * P0[1] + 2 * it * t * C[1] + t * t * P1[1], t]);
    }
    for (let y = 0; y < S.h; y++) for (let x = 0; x < S.w; x++) {
      let best = 1e9, bt = 0;
      for (const q of pts) { const d = (x + 0.5 - q[0]) ** 2 + (y + 0.5 - q[1]) ** 2; if (d < best) { best = d; bt = q[2]; } }
      const w = w0 + (w1 - w0) * bt + (wm - (w0 + w1) / 2) * Math.sin(Math.PI * bt);
      const d = Math.sqrt(best);
      if (d > w) continue;
      const c = colFn(d / w, bt);
      if (c) S.px(x, y, c);
    }
  }

