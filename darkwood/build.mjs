#!/usr/bin/env node
// Builds Darkwood into a single self-contained file (index.html) that runs
// offline from anywhere, plus dev.html which loads src/ files directly.
//
//   node build.mjs
import fs from 'fs';
import path from 'path';
import url from 'url';

const root = path.dirname(url.fileURLToPath(import.meta.url));
const srcDir = path.join(root, 'src');
const files = fs.readdirSync(srcDir).filter(f => f.endsWith('.js')).sort();
const template = fs.readFileSync(path.join(srcDir, 'template.html'), 'utf8');

const banner = `<!--
  DARKWOOD — Arena of Champions  (built ${new Date().toISOString().slice(0, 10)})
  Generated by build.mjs from src/. To change the game, edit src/ (game data
  lives in src/10_data.js) and run:  node build.mjs
-->`;

const inline = files.map(f => {
  const code = fs.readFileSync(path.join(srcDir, f), 'utf8').replace(/<\/script/gi, '<\\/script');
  return `<script>\n// ---- ${f} ----\n${code}\n</script>`;
}).join('\n');

fs.writeFileSync(path.join(root, 'index.html'), template.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + banner).replace('<!--SCRIPTS-->', inline));
fs.writeFileSync(path.join(root, 'dev.html'), template.replace('<!--SCRIPTS-->', files.map(f => `<script src="src/${f}"></script>`).join('\n')));

const size = fs.statSync(path.join(root, 'index.html')).size;
console.log(`built index.html (${(size / 1024).toFixed(0)} KB, ${files.length} modules) and dev.html`);
